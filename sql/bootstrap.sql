CREATE DATABASE IF NOT EXISTS MORTGAGE_DB;
CREATE SCHEMA IF NOT EXISTS MORTGAGE_DB.BRONZE;
CREATE SCHEMA IF NOT EXISTS MORTGAGE_DB.SILVER;
CREATE SCHEMA IF NOT EXISTS MORTGAGE_DB.GOLD;
CREATE SCHEMA IF NOT EXISTS MORTGAGE_DB.AUDIT;
CREATE WAREHOUSE IF NOT EXISTS MORTGAGE_WH WITH WAREHOUSE_SIZE='XSMALL' AUTO_SUSPEND=60 AUTO_RESUME=TRUE INITIALLY_SUSPENDED=TRUE;

CREATE FILE FORMAT IF NOT EXISTS MORTGAGE_DB.BRONZE.JSON_FF TYPE=JSON STRIP_OUTER_ARRAY=TRUE;
CREATE FILE FORMAT IF NOT EXISTS MORTGAGE_DB.BRONZE.CSV_FF TYPE=CSV SKIP_HEADER=1 FIELD_OPTIONALLY_ENCLOSED_BY='"' EMPTY_FIELD_AS_NULL=TRUE;
CREATE STAGE IF NOT EXISTS MORTGAGE_DB.BRONZE.MORTGAGE_STAGE;

CREATE TABLE IF NOT EXISTS MORTGAGE_DB.BRONZE.RAW_APPLICATIONS (
  PAYLOAD VARIANT NOT NULL,
  SOURCE_FILE VARCHAR,
  INGESTED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);
CREATE TABLE IF NOT EXISTS MORTGAGE_DB.BRONZE.RAW_CREDIT_BUREAU (
  APPLICANT_ID VARCHAR,
  SSN VARCHAR,
  FICO_SCORE NUMBER(3,0),
  MONTHLY_DEBT NUMBER(12,2),
  SOURCE_FILE VARCHAR,
  INGESTED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);
CREATE TABLE IF NOT EXISTS MORTGAGE_DB.AUDIT.TECHNICAL_REJECTIONS (
  APPLICATION_ID VARCHAR,
  APPLICANT_ID VARCHAR,
  REJECTION_REASON VARCHAR,
  SOURCE_PAYLOAD VARIANT,
  REJECTED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE ROLE IF NOT EXISTS MORTGAGE_ANALYST;
CREATE ROLE IF NOT EXISTS MORTGAGE_COMPLIANCE;
CREATE MASKING POLICY IF NOT EXISTS MORTGAGE_DB.BRONZE.SSN_MASK AS (VAL VARCHAR)
  RETURNS VARCHAR -> CASE
    WHEN CURRENT_ROLE() IN ('MORTGAGE_COMPLIANCE','ACCOUNTADMIN','SYSADMIN') THEN VAL
    WHEN VAL IS NULL THEN NULL
    ELSE 'XXX-XX-XXXX'
  END;
ALTER TABLE MORTGAGE_DB.BRONZE.RAW_CREDIT_BUREAU MODIFY COLUMN SSN SET MASKING POLICY MORTGAGE_DB.BRONZE.SSN_MASK;
